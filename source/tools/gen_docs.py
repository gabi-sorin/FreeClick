#!/usr/bin/env python3
"""docs/reference.md -> src/com/freeclick/core/script/DocsText.java (the in-app documentation).

The Markdown stays the one place where the documentation is written (readable on its own too);
the app gets it as Java string pieces (each under the class-file limit for one string)."""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "docs", "reference.md"), encoding="utf-8").read()

def lit(s):
    out = []
    for ch in s:
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        elif ch == "\r": continue
        elif ord(ch) < 32 or ord(ch) > 126: out.append("\\u%04x" % ord(ch)) if ord(ch) <= 0xFFFF else out.append(ch)
        else: out.append(ch)
    return "".join(out)

chunks, cur = [], []
size = 0
for line in src.splitlines(True):
    if size + len(line) > 8000 and cur:
        chunks.append("".join(cur)); cur = []; size = 0
    cur.append(line); size += len(line)
if cur: chunks.append("".join(cur))

java = ["package com.freeclick.core.script;", "",
        "/** GENERATED by tools/gen_docs.py from docs/reference.md: edit the Markdown, not this file. */",
        "final class DocsText {", "    private DocsText() {}", "",
        "    static String text() {", "        StringBuilder b = new StringBuilder(%d);" % len(src)]
for c in chunks:
    java.append('        b.append("%s");' % lit(c))
java += ["        return b.toString();", "    }", "}", ""]
out = os.path.join(ROOT, "src", "com", "freeclick", "core", "script", "DocsText.java")
new = "\n".join(java)
if not os.path.exists(out) or open(out, encoding="utf-8").read() != new:
    open(out, "w", encoding="utf-8").write(new)
